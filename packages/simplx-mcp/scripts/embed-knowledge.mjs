// LAB-257 T259: embeds src/knowledge/*.md into src/knowledge/embedded.ts so the
// published package (dist only) carries the guide without copying assets.
// Run before tsc (see package.json "build"); test/knowledge.test.ts fails when
// the embedded copy is stale.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
const dir = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "knowledge");
const files = { META_GUIDE: "guide.md", META_TYPES_REFERENCE: "types-reference.md" };
let out = "// GENERATED by scripts/embed-knowledge.mjs — do not edit; edit the .md next to it.\n";
for (const [name, file] of Object.entries(files)) {
  out += `export const ${name} = ${JSON.stringify(readFileSync(join(dir, file), "utf8"))};\n`;
}
writeFileSync(join(dir, "embedded.ts"), out);
console.log("[simplx-mcp] knowledge embedded:", Object.values(files).join(", "));
